// Small inline SVG icons, so we do not need an icon library.
// Each icon takes a className for size and color, e.g. <CheckIcon className="h-4 w-4" />.
// They are decorative (aria-hidden), so always pair them with visible text.
type IconProps = { className?: string };

function Svg({ className, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      {children}
    </svg>
  );
}

